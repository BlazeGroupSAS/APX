// Hidden process launch on Windows.
//
// THE PROBLEM THIS FILE OWNS. `windowsHide` hides a window only for the process
// you spawn — and only while Node keeps it inside its job object. Two Windows
// process shapes need more than the flag:
//
//   - AUTOSTART: a Run-key value like `node.exe script` gets a console from
//     explorer at every logon (node.exe is a console-subsystem app). For the
//     daemon that console stays open the whole session.
//   - BACKGROUND JOBS: a detached cmd has NO console, so the first console app
//     underneath it allocates a VISIBLE one; a non-detached cmd dies with the
//     daemon because Node kills non-detached children on exit. Neither direct
//     shape satisfies "no window AND survives restart AND killable tree".
//
// THE MECHANISM, in three pieces:
//
//   1. hidden-run.js + win-autostart-launch.cjs — the autostart hop.
//      wscript.exe (GUI subsystem, always present at logon, never has a
//      console) runs the JScript with ONE argument: a UTF-16 payload file
//      holding {node, launcher, cmd}. The JScript ShellExecutes `node` with
//      just two OWN paths — the launcher script and the payload — never the
//      real argv: wscript eats argv starting with '//' as WSH switches, and
//      any args string can be envsubst-expanded or deformed by re-quoting.
//      win-autostart-launch.cjs then reads cmd[] from the payload and calls
//      spawn(cmd[0], cmd.slice(1)) — the target's argv stays structured all
//      the way, so '%', '&', embedded quotes, empty strings and '//…' all
//      arrive verbatim. `//B` keeps wscript silent if the script or payload
//      is missing — no modal error dialog on every login.
//   2. win-bgjob-host.cjs — a tiny node host the daemon spawns DETACHED (so it
//      outlives restarts). It has no console of its own; it spawns the job's
//      cmd with windowsHide, which gives cmd one auto-allocated HIDDEN console
//      the whole tree shares, and bridges stdout/stderr/exit to the daemon
//      over a named pipe. The host is also the tree root: taskkill /T on its
//      pid stops everything, and if the host dies its job-object membership
//      takes the tree with it.
//   3. pick-dir.js — BrowseForFolder from wscript itself: the dialog is a COM
//      window on the GUI host, so it is visible with NO powershell, cmd,
//      conhost or WindowsTerminal anywhere in the tree. The prompt rides in
//      through the environment, not argv — an argv item starting with '//'
//      would be eaten by the WSH option parser and silently become a switch.
//      (The earlier powershell + -WindowStyle Hidden form still got hosted
//      in a visible Terminal.)
//
// Nothing here is for POSIX callers; every entry point is win32-gated upstream.
import fs from "node:fs";
import path from "node:path";
import net from "node:net";
import { spawn } from "node:child_process";
import { EventEmitter } from "node:events";
import { fileURLToPath } from "node:url";
import { apxHome } from "#core/config/paths.js";

const HERE = path.dirname(fileURLToPath(import.meta.url));

/** The committed job host — the node half of the Windows background bridge. */
export function jobHostPath() {
  return path.join(HERE, "win-bgjob-host.cjs");
}

/** Absolute wscript.exe — System32 is always on the logon PATH, but a Run
 *  value or spawn should not depend on lookup order. */
export function wscriptPath(env = process.env) {
  const root = env.SystemRoot || env.windir || "C:\\Windows";
  return path.join(root, "System32", "wscript.exe");
}

function runtimeDir() {
  return path.join(apxHome(), "autostart");
}

export function hiddenRunnerPath() {
  return path.join(runtimeDir(), "hidden-run.js");
}

export function pickDirScriptPath() {
  return path.join(runtimeDir(), "pick-dir.js");
}

// ASCII-only, forever: the only string this script builds is two of OUR OWN
// paths (the node launcher + the payload) — never a target argv. Those paths
// are validated %-free at write time, so nothing on this command line can be
// expanded or reparsed. The real argv never leaves JSON.
const HIDDEN_RUNNER_JS =
  "// APX hidden launcher. Do not edit -- regenerated by install/uninstall.\n" +
  "try {\n" +
  "  var fso = new ActiveXObject(\"Scripting.FileSystemObject\");\n" +
  "  var f = fso.OpenTextFile(WScript.Arguments(0), 1, false, -1);\n" +
  "  var spec = eval(\"(\" + f.ReadAll() + \")\");\n" +
  "  f.Close();\n" +
  "  // Stale autostart must die silently: ShellExecute on a missing exe pops\n" +
  "  // a 'file not found' modal that //B cannot suppress -- it is the shell's\n" +
  "  // dialog, not WSH's. Any missing hop piece means: do not start.\n" +
  "  if (!fso.FileExists(spec.node) || !fso.FileExists(spec.launcher)) throw 0;\n" +
  "  new ActiveXObject(\"Shell.Application\").ShellExecute(\n" +
  "    spec.node, '\"' + spec.launcher + '\" \"' + WScript.Arguments(0) + '\"',\n" +
  "    \"\", \"open\", 0);\n" +
  "} catch (e) {\n" +
  "  // Missing or corrupt payload: exit quietly. A modal here would pop at every login.\n" +
  "}\n";

// wscript has no stdout — the picked path is written to the file named by
// Arguments(0), UTF-16 so non-ASCII folders survive. The prompt is NOT an
// argument: an argv item starting with '//' is eaten by the WSH option
// parser, so the prompt arrives through the APX_PICK_PROMPT env var.
const PICK_DIR_JS =
  "// APX folder picker. Runs under wscript -- the dialog is the point.\n" +
  'var env = new ActiveXObject("WScript.Shell").Environment("PROCESS");\n' +
  'var f = new ActiveXObject("Shell.Application").BrowseForFolder(0, env.Item("APX_PICK_PROMPT"), 0, 0);\n' +
  "if (f) {\n" +
  '  var out = new ActiveXObject("Scripting.FileSystemObject").CreateTextFile(WScript.Arguments(0), true, true);\n' +
  "  out.Write(f.Self.Path);\n" +
  "  out.Close();\n" +
  "}\n";

/** Write `contents` to `dest` atomically — a half-written launcher must never
 *  be what logon runs. Returns dest. */
function writeAtomic(dest, contents, encoding = "utf8") {
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  const tmp = dest + ".tmp-" + process.pid;
  fs.writeFileSync(tmp, contents, encoding);
  fs.renameSync(tmp, dest);
  return dest;
}

function ensureScript(dest, contents) {
  try {
    if (fs.readFileSync(dest, "utf8") === contents) return dest;
  } catch { /* missing or unreadable — write it */ }
  return writeAtomic(dest, contents);
}

export function ensureHiddenRunner() {
  return ensureScript(hiddenRunnerPath(), HIDDEN_RUNNER_JS);
}

export function ensurePickDirScript() {
  return ensureScript(pickDirScriptPath(), PICK_DIR_JS);
}

export function autostartPayloadPath(name) {
  return path.join(runtimeDir(), `${name}.json`);
}

/** The committed node-side launcher — reads the payload and spawns cmd[]
 *  with structured argv. */
export function autostartLauncherPath() {
  return path.join(HERE, "win-autostart-launch.cjs");
}

/**
 * Write the autostart payload for `argv` and return the wscript argument
 * vector: ["//B", "//Nologo", hidden-run.js, <payload>]. The payload is a
 * UTF-16 JSON {node, launcher, cmd} — the ONLY thing on wscript's command
 * line besides its own switches, and the only thing on the intermediary
 * node's command line is two APX-owned paths. The target's argv travels as
 * JSON and is spawned structured, so it is never parsed as a string.
 *
 * `argv` must be a non-empty array of strings; the APX-owned paths on the
 * intermediary hop (payload, launcher, node.exe) must not contain '%' —
 * the one place an envsubst could still bite. Anything outside the contract
 * is rejected, never silently transformed.
 */
export function wscriptArgv(name, argv) {
  if (!Array.isArray(argv) || argv.length === 0 || argv.some((a) => typeof a !== "string")) {
    throw new Error(`autostart argv for "${name}" must be a non-empty array of strings`);
  }
  const payload = autostartPayloadPath(name);
  const launcher = autostartLauncherPath();
  for (const own of [payload, launcher, process.execPath]) {
    if (own.includes("%")) {
      throw new Error(`autostart hop path contains '%' — the launcher's args string cannot carry it safely: ${own}`);
    }
  }
  const spec = { node: process.execPath, launcher, cmd: argv };
  // UTF-16LE, no BOM: the launcher opens the file with TristateTrue and a
  // literal BOM inside the string would break the eval'd JSON.
  writeAtomic(payload, JSON.stringify(spec), "utf16le");
  return ["//B", "//Nologo", ensureHiddenRunner(), payload];
}

/** The string a HKCU\...\Run value should hold for `argv`. */
export function wscriptRunValue(name, argv, env = process.env) {
  const q = (s) => `"${String(s)}"`;
  return [wscriptPath(env), ...wscriptArgv(name, argv)].map(q).join(" ");
}

/** Best-effort payload cleanup on uninstall — a left-behind file is inert
 *  once the Run value is gone. */
export function removeAutostartPayload(name) {
  try { fs.unlinkSync(autostartPayloadPath(name)); } catch { /* already gone */ }
}

/** What the OS handed back from the picker, normalized with Windows path
 *  semantics — `C:\` must stay `C:\`, never collapse to the drive-relative
 *  `C:` (which resolves against the daemon's cwd). Trailing separators on
 *  non-root paths come off. */
export function normalizePickedPath(p) {
  if (!p) return "";
  const n = path.win32.normalize(String(p));
  const root = path.win32.parse(n).root; // "C:\\" or "\\\\server\\share\\"
  return n.length > root.length ? n.replace(/[\\/]+$/, "") : n;
}

/** How long the daemon waits for the job host to come up on the pipe before
 *  declaring the launch failed. Generous: cold node start is ~200 ms. */
const HOST_CONNECT_MS = 15_000;

function specDir() {
  return path.join(apxHome(), "background-jobs");
}

/**
 * Launch a job shell so it is hidden, killable, and daemon-independent — the
 * Windows-only shape. The daemon spawns win-bgjob-host DETACHED (survives a
 * restart); the host spawns `file` with the given options (windowsHide → one
 * hidden console for the whole tree) and relays stdio/exit over a named pipe.
 *
 * Returns a ChildProcess-shaped EventEmitter whose `pid` is the HOST's —
 * deliberately: the host is the tree root, so taskkill /T on it stops the
 * shell and every grandchild, and a dead host takes the tree down through
 * the job object. stdout/stderr are plain data emitters; "close" fires with
 * the shell's exit code; "error" fires when the host itself could not start.
 *
 * `spawnFn` is injectable for tests — it is used for the host spawn only.
 */
export function spawnWindowsJob({ jobId, file, args, options = {}, cwd, spawnFn = spawn }) {
  const specPath = path.join(specDir(), `launch-${jobId}.json`);
  fs.mkdirSync(path.dirname(specPath), { recursive: true });
  const pipe = `\\\\.\\pipe\\apx-bgjob-${jobId}-${process.pid}`;
  fs.writeFileSync(specPath, JSON.stringify({ pipe, file, args, options, cwd: cwd || null }));

  const host = spawnFn(process.execPath, [jobHostPath(), specPath], {
    detached: true,
    windowsHide: true,
    stdio: "ignore",
  });
  host.unref?.();

  const remote = new EventEmitter();
  remote.stdout = new EventEmitter();
  remote.stderr = new EventEmitter();
  remote.pid = host.pid;
  remote.unref = () => {};
  remote.kill = (signal) => {
    try { return process.kill(remote.pid, signal); } catch { return false; }
  };

  let connected = false;
  let sawExit = false;
  let settled = false;
  const server = net.createServer((conn) => {
    connected = true;
    clearTimeout(connectTimer);
    let buf = "";
    conn.on("data", (d) => {
      buf += d;
      let i;
      while ((i = buf.indexOf("\n")) >= 0) {
        const line = buf.slice(0, i).trim();
        buf = buf.slice(i + 1);
        if (!line) continue;
        let frame;
        try { frame = JSON.parse(line); } catch { continue; }
        if (frame.t === "out") remote.stdout.emit("data", Buffer.from(frame.d, "base64"));
        else if (frame.t === "err") remote.stderr.emit("data", Buffer.from(frame.d, "base64"));
        else if (frame.t === "exit") {
          sawExit = true;
          if (frame.error) remote.emit("error", new Error(frame.error));
          finish(() => remote.emit("close", frame.code, frame.signal));
        }
      }
    });
    conn.on("close", () => {
      // The host went away without reporting an exit — it died or was killed.
      // Either way the tree is gone; report the close so the record settles.
      if (!sawExit) finish(() => remote.emit("close", null, null));
    });
  });
  server.unref?.();
  server.listen(pipe);

  const finish = (emit) => {
    if (settled) return;
    settled = true;
    try { server.close(); } catch { /* best-effort */ }
    try { fs.unlinkSync(specPath); } catch { /* host usually deletes it */ }
    emit();
  };

  const connectTimer = setTimeout(() => {
    if (!connected) {
      try { host.kill?.(); } catch { /* already gone */ }
      finish(() => {
        remote.emit("error", new Error("background job host never connected"));
        remote.emit("close", null, null);
      });
    }
  }, HOST_CONNECT_MS);
  connectTimer.unref?.();

  // A host that dies before ever connecting means the launch itself failed —
  // surface it through the same channels a failed spawn would use.
  host.on?.("error", (e) => {
    if (!connected) finish(() => { remote.emit("error", e); remote.emit("close", null, null); });
  });
  host.on?.("exit", () => {
    if (!connected) {
      finish(() => {
        remote.emit("error", new Error("background job host exited before connecting"));
        remote.emit("close", null, null);
      });
    }
  });

  return remote;
}
